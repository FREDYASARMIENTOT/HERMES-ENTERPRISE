<#
.SYNOPSIS
    Repara la instalación del módulo Hermes.
.DESCRIPTION
    Verifica y repara la estructura de archivos del módulo Hermes.Commands,
    recreando archivos faltantes o corruptos.
    Función canónica (RC63) — PRIORITY COMMAND.
.PARAMETER ModulePath
    Ruta al módulo Hermes.Commands. Por defecto busca en $env:PSModulePath.
.PARAMETER Force
    Reemplaza todos los archivos incluso si existen.
.EXAMPLE
    Repair-HermesInstallation
#>
function Repair-HermesInstallation {
    [CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'Medium')]
    param(
        [Parameter(Mandatory = $false)]
        [string]$ModulePath,

        [Parameter(Mandatory = $false)]
        [switch]$Force
    )

    if ($PSCmdlet.ShouldProcess('Hermes.Commands', 'Repair Hermes installation')) {
        Write-Host "[..] Repairing Hermes.Commands installation ..." -ForegroundColor Yellow

        # Resolve module path
        if (-not $ModulePath) {
            $module = Get-Module Hermes.Commands -ListAvailable | Select-Object -First 1
            if ($module) {
                $ModulePath = $module.ModuleBase
            } else {
                Write-Error "Hermes.Commands module not found. Specify -ModulePath or install the module first."
                return
            }
        }

        Write-Host "[..] Module path: $ModulePath" -ForegroundColor Cyan

        # Check required directories
        $requiredDirs = @(
            'Public',
            'Private',
            'lib'
        )

        $repaired = $false
        foreach ($dir in $requiredDirs) {
            $dirPath = Join-Path $ModulePath $dir
            if (-not (Test-Path $dirPath)) {
                New-Item -ItemType Directory -Path $dirPath -Force | Out-Null
                Write-Host "[OK] Created missing directory: $dir" -ForegroundColor Green
                $repaired = $true
            }
        }

        # Check required Public files (stubs)
        $requiredFiles = @(
            'Get-HermesVersion.ps1',
            'Get-HermesConfiguration.ps1',
            'Set-HermesConfiguration.ps1',
            'New-HermesProject.ps1',
            'Update-HermesProject.ps1',
            'Repair-HermesInstallation.ps1'
        )

        foreach ($file in $requiredFiles) {
            $filePath = Join-Path $ModulePath 'Public' $file
            if (-not (Test-Path $filePath) -or $Force) {
                if (-not (Test-Path $filePath)) {
                    Write-Host "[..] Creating stub for missing file: $file" -ForegroundColor Yellow
                    "# Stub: $file`n# Auto-generated by Repair-HermesInstallation" | Out-File -FilePath $filePath -Encoding UTF8
                    Write-Host "[OK] Created stub: $file" -ForegroundColor Green
                    $repaired = $true
                }
            }
        }

        # Verify module manifest
        $manifestPath = Join-Path $ModulePath 'Hermes.Commands.psd1'
        if (-not (Test-Path $manifestPath)) {
            Write-Error "Module manifest not found: $manifestPath"
            return
        }

        Write-Host "[OK] Module manifest found: $manifestPath" -ForegroundColor Green

        # Re-import module
        Remove-Module Hermes.Commands -Force -ErrorAction SilentlyContinue
        Import-Module $manifestPath -Force -ErrorAction Stop
        Write-Host "[OK] Module re-imported successfully" -ForegroundColor Green

        if ($repaired) {
            Write-Host "[OK] Installation repaired successfully" -ForegroundColor Green
        } else {
            Write-Host "[OK] Installation is healthy — no repair needed" -ForegroundColor Green
        }
    }
}